#!/usr/bin/env python3
"""Canonical AGENTS.md/CLAUDE.md rules-file helpers — single source of truth.

Every ycc skill that detects or writes the AGENTS.md/CLAUDE.md pointer pair
must use this module (via the thin Bash entrypoint ``rules-pointer.sh`` in the
same directory, or by importing it directly). Consumers: ``init`` (profile,
render-template.py, migrate-rules.py) and ``release-model``
(pointer-targets.sh). The module is copied verbatim into every generated
runtime bundle (``skills/_shared/scripts/`` for Claude/Cursor,
``shared/scripts/`` for Codex/opencode, ``ycc-shared/scripts/`` for the
cross-tool agents target), so it must stay self-contained: standard library
only, no imports outside this file.

Requires Python 3.11+. Text readers are BOM- and CRLF-tolerant
(``utf-8-sig``-equivalent normalization) so Windows-edited rules files parse
identically through every parser path.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

MIN_PYTHON = (3, 11)

IMPORT_RE = re.compile(r"^\s*@(?:\./)?AGENTS\.md\s*$")
COMMENT_RE = re.compile(r"<!--.*?-->", re.DOTALL)
FENCE_RE = re.compile(r"^\s*(`{3,}|~{3,})")

# The exact pointer line of the CLAUDE.md -> AGENTS.md shim. The init template
# (CLAUDE.md.tmpl -> {{CLAUDE_MD_SHIM}}), migrate-rules.py and any audit/verify
# step all read this constant; never spell the line out elsewhere.
CLAUDE_SHIM_LINE = "@AGENTS.md"

# Release-model pointer targets, in listing order.
POINTER_TARGET_FILES = ("CLAUDE.md", "AGENTS.md", ".github/copilot-instructions.md")

# Heuristic for a legacy (inverted) pointer AGENTS.md: short and mentioning
# CLAUDE.md. Anything longer or without the phrase is custom content.
LEGACY_POINTER_MAX_LINES = 40

# Exact legacy pointer boilerplate recognised by migrate-rules.py. Mentions of
# CLAUDE.md in genuine rules are never retired by these sets.
LEGACY_POINTER_SIMPLE_LINES = {
    "The canonical agent rules live in CLAUDE.md.",
    "The canonical agent rules for this repository live in [`CLAUDE.md`](CLAUDE.md).",
}
LEGACY_POINTER_BODY = """The canonical agent rules for this repository live in [`CLAUDE.md`](CLAUDE.md).

This file exists so agent-runtime tools that default to `AGENTS.md` (Cursor, Windsurf,
OpenAI Codex, etc.) pick up the same rules without duplicating prose.

## Agent-runtime notes

- Cursor: also reads `.cursor/rules/project.mdc` (same content, MDC-formatted).
- When an MCP server is available for the task, prefer it; read each tool's schema first.
- For deep analysis of this repository, start with `CLAUDE.md` and the stack overview.

## Sync policy

`CLAUDE.md` is the source of truth. Do not edit this file except to add
agent-runtime-specific notes. Never duplicate `CLAUDE.md` content here."""


def require_python(name: str = "rules-pointer") -> None:
    """Abort with a readable message when the interpreter is below MIN_PYTHON."""
    if sys.version_info < MIN_PYTHON:
        want = ".".join(str(p) for p in MIN_PYTHON)
        found = sys.version.split()[0]
        print(
            f"{name}: python3 {want}+ required, found {found}; "
            "install a newer python3 (or point 'python3' at one) and retry",
            file=sys.stderr,
        )
        sys.exit(1)


def read_text_relaxed(path: Path) -> tuple[str, bool]:
    """Read a rules file tolerating a UTF-8 BOM.

    Returns ``(text_without_bom, had_bom)``.
    """
    raw = path.read_bytes()
    had_bom = raw.startswith(b"\xef\xbb\xbf")
    if had_bom:
        raw = raw[3:]
    return raw.decode("utf-8"), had_bom


def detect_agents_import(text: str) -> bool:
    """True when ``text`` contains a live standalone ``@AGENTS.md`` import.

    Semantics (canonical — every consumer must use this function):

    * HTML comments are stripped before scanning.
    * Lines inside fenced code blocks (``` or ~~~, matching open/close) never
      count.
    * Only a line consisting solely of ``@AGENTS.md`` (optionally ``@./AGENTS.md``,
      with surrounding whitespace) is an import.
    * ``\\r`` line endings and a leading UTF-8 BOM are normalised first.
    """
    text = text.lstrip("\ufeff").replace("\r\n", "\n").replace("\r", "\n")
    text = COMMENT_RE.sub("", text)
    fence = ""
    for line in text.split("\n"):
        marker = FENCE_RE.match(line)
        if marker:
            if not fence:
                fence = marker.group(1)
            elif marker.group(1)[0] == fence[0] and len(marker.group(1)) >= len(fence):
                fence = ""
            continue
        if fence:
            continue
        if IMPORT_RE.fullmatch(line):
            return True
    return False


def detect_eol(text: str) -> str:
    """Return the dominant line ending of ``text`` ('\\n' or '\\r\\n')."""
    return "\r\n" if text.count("\r\n") >= text.count("\n") - text.count("\r\n") else "\n"


def split_sections(text: str) -> list[list[str]]:
    """Split ``text`` into sections at markdown H1/H2 headings outside fences.

    The preamble (everything before the first heading, normally the title and
    intro) is returned as the first section. A heading that appears mid-file
    starts its own section, so an H1 like ``# Claude Code setup`` cannot be
    swallowed by the preceding section.
    """
    lines = text.split("\n")
    sections: list[list[str]] = []
    current: list[str] = []
    fence = ""
    for line in lines:
        stripped_bare = line.replace("\r", "")
        marker = FENCE_RE.match(stripped_bare)
        if marker:
            if not fence:
                fence = marker.group(1)
            elif marker.group(1)[0] == fence[0] and len(marker.group(1)) >= len(fence):
                fence = ""
            current.append(line)
            continue
        is_heading = not fence and re.match(r"^#{1,2} \S", stripped_bare) is not None
        if is_heading and current:
            sections.append(current)
            current = [line]
        else:
            current.append(line)
    if current:
        sections.append(current)
    return sections


def heading_of(section: list[str]) -> str | None:
    """The ``#``/``##`` heading line of a section, or None for the preamble."""
    first = section[0].replace("\r", "") if section else ""
    if re.match(r"^#{1,2} \S", first):
        return first
    return None


def is_legacy_agents_pointer(text: str) -> bool:
    """True when an AGENTS.md is one of the known legacy pointer boilerplates.

    Only exact legacy text matches; genuine rules mentioning CLAUDE.md do not.
    """
    meaningful = [line.strip() for line in text.splitlines() if line.strip()]
    simple = len(meaningful) == 2 and meaningful[0].startswith("# ") and meaningful[1] in LEGACY_POINTER_SIMPLE_LINES
    full = "\n".join(text.strip().splitlines()[1:]).strip() == LEGACY_POINTER_BODY
    return simple or full


def is_short_agents_pointer(text: str) -> bool:
    """Profile heuristic for a legacy pointer AGENTS.md: short + mentions CLAUDE.md."""
    return len(text.splitlines()) <= LEGACY_POINTER_MAX_LINES and "claude.md" in text.lower()


def claude_md_imports_agents(root: Path) -> bool:
    """True when ``root/CLAUDE.md`` exists and live-imports ``AGENTS.md``."""
    claude = root / "CLAUDE.md"
    if not claude.is_file():
        return False
    text, _had_bom = read_text_relaxed(claude)
    return detect_agents_import(text)


def pointer_targets(root: Path) -> tuple[list[str], str | None]:
    """Existing release-pointer files under ``root``.

    Returns ``(targets, error)``. When CLAUDE.md live-imports AGENTS.md the
    canonical file is AGENTS.md and CLAUDE.md is left out. A dangling import
    is an error (repair the import first); nothing is ever created here.
    """
    imports = claude_md_imports_agents(root)
    if imports and not (root / "AGENTS.md").is_file():
        return [], "pointer-targets: CLAUDE.md imports missing AGENTS.md; repair the import first"
    targets = []
    for rel in POINTER_TARGET_FILES:
        if rel == "CLAUDE.md" and imports:
            continue
        if (root / rel).is_file():
            targets.append(rel)
    return targets, None


def claude_shim(notes: str = "") -> str:
    """Render the canonical shim with optional notes; callers enforce size budgets."""
    body = CLAUDE_SHIM_LINE + "\n"
    notes = notes.strip("\n")
    if notes:
        body += "\n## Claude-only notes\n\n" + notes + "\n"
    return body


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="rules-pointer", description="Canonical rules-file detection and shim rendering"
    )
    sub = parser.add_subparsers(dest="command", required=True)
    for name in ("imports-agents", "targets", "profile"):
        p = sub.add_parser(name)
        p.add_argument("--repo", required=True)
    shim = sub.add_parser("claude-md-shim")
    shim.add_argument("--notes", default="", help="notes text, or '-' for stdin")
    args = parser.parse_args(argv)

    if args.command == "claude-md-shim":
        notes = sys.stdin.read() if args.notes == "-" else args.notes
        sys.stdout.write(claude_shim(notes))
        return 0

    root = Path(args.repo)
    if not root.is_dir():
        print(f"rules-pointer: directory not found: {args.repo}", file=sys.stderr)
        return 1
    if args.command == "profile":
        agents = root / "AGENTS.md"
        legacy = is_short_agents_pointer(read_text_relaxed(agents)[0]) if agents.is_file() else False
        imports = claude_md_imports_agents(root)
        print(f"agents_md_is_pointer={str(legacy).lower()}")
        print(f"claude_md_imports_agents={str(imports).lower()}")
        return 0
    if args.command == "imports-agents":
        print(f"imports_agents={'true' if claude_md_imports_agents(root) else 'false'}")
        return 0
    targets, error = pointer_targets(root)
    if error is not None:
        print(error, file=sys.stderr)
        return 1
    for rel in targets:
        print(rel)
    return 0


if __name__ == "__main__":
    require_python()
    try:
        sys.exit(main())
    except (OSError, UnicodeDecodeError) as exc:
        print(f"rules-pointer: cannot read rules file: {exc}", file=sys.stderr)
        sys.exit(1)
